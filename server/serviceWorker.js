// Builds public sw.js at build time: the app shell and every bundled file are
// cached on install, so cards, captions and lessons open without a network.
// Large models and sign data are cached the first time they are used.

export function serviceWorkerSource(files, version) {
  return `// Generated by vite.config.ts (server/serviceWorker.js). Do not edit.
const VERSION = ${JSON.stringify(version)};
const SHELL = "parlance-shell-" + VERSION;
const RUNTIME = "parlance-runtime-v1";
const PRECACHE = ${JSON.stringify(files)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(SHELL).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith("parlance-shell-") && key !== SHELL).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/api/") || url.pathname.startsWith("/recognition")) return;

  // Pages: the network first (fresh deploys), the cached app shell offline.
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).catch(() => caches.match("/index.html", { cacheName: SHELL }).then((hit) => hit || Response.error())),
    );
    return;
  }

  // Everything else: cache first; fill the runtime cache on first use.
  event.respondWith(
    caches.match(request).then((hit) => {
      if (hit) return hit;
      return fetch(request).then((response) => {
        if (response.ok && response.type === "basic") {
          const copy = response.clone();
          void caches.open(RUNTIME).then((cache) => cache.put(request, copy));
        }
        return response;
      });
    }),
  );
});
`;
}
